package dev.noisefield.audio

/** Один биквад: y = b0·w + b1·z1 + b2·z2, где w = x − a1·z1 − a2·z2. */
class Biquad(
    @JvmField val b0: Double,
    @JvmField val b1: Double,
    @JvmField val b2: Double,
    @JvmField val a1: Double,
    @JvmField val a2: Double,
)

/**
 * A-взвешивание по IEC 61672 — каскад из трёх IIR-биквадов, прямая форма II, Double.
 *
 * Состояние сохраняется между вызовами и НЕ сбрасывается на границе буфера
 * (спецификация, §2.2 и §8): сброс даёт щелчок на каждом стыке и систематическое
 * завышение уровня.
 *
 * Полюса аналогового прототипа стандартные — 20.598997 / 107.65265 / 737.86223 /
 * 12194.217 Гц — и не подгоняются ни под какой тест. Приложение имеет смысл ровно
 * настолько, насколько оно сравнимо с прибором класса 2; фильтр, подогнанный под
 * собственный допуск, эту сравнимость теряет.
 *
 * Разложение прототипа:
 *   секция 0:  s² / (s + w1)²          — двойной полюс на нижней частоте
 *   секция 1:  s² / (s + w4)²          — двойной полюс на верхней частоте
 *   секция 2:  K / ((s + w2)(s + w3))  — и нормировка усиления к 0 дБ на 1 кГц
 * билинейно преобразованных на 44100 Гц, без предыскажения частоты.
 *
 * Проверяется тестом [dev.noisefield.AudioTractTest].
 */
class AWeightingFilter {

    private val z1 = DoubleArray(SECTIONS.size)
    private val z2 = DoubleArray(SECTIONS.size)

    /** Прогон одного отсчёта через каскад. Отсчёт нормирован в −1..1. */
    fun process(sample: Double): Double {
        var x = sample
        for (i in SECTIONS.indices) {
            val s = SECTIONS[i]
            val w = x - s.a1 * z1[i] - s.a2 * z2[i]
            x = s.b0 * w + s.b1 * z1[i] + s.b2 * z2[i]
            z2[i] = z1[i]
            z1[i] = w
        }
        return x
    }

    /**
     * Сброс состояния. Вызывается только при открытии нового тракта,
     * никогда — между буферами внутри одного замера.
     */
    fun reset() {
        z1.fill(0.0)
        z2.fill(0.0)
    }

    companion object {
        /** Частота дискретизации, под которую посчитаны коэффициенты. */
        const val SAMPLE_RATE = 44100

        val SECTIONS: Array<Biquad> = arrayOf(
            Biquad(
                b0 = 0.99707158767771475,
                b1 = -1.9941431753554295,
                b2 = 0.99707158767771475,
                a1 = -1.9941388812663283,
                a2 = 0.99414746944453092,
            ),
            Biquad(
                b0 = 0.28636842000906276,
                b1 = -0.57273684001812553,
                b2 = 0.28636842000906276,
                a1 = -0.14053608242071078,
                a2 = 0.0049375976155402032,
            ),
            Biquad(
                b0 = 0.89513531257746115,
                b1 = 1.7902706251549223,
                b2 = 0.89513531257746115,
                a1 = -1.8849012174287920,
                a2 = 0.88642147181616737,
            ),
        )

        /** Табличная A-кривая для 31.5 / 63 / … / 8000 Гц. Используется тестом. */
        val REFERENCE_FREQUENCIES = doubleArrayOf(31.5, 63.0, 125.0, 250.0, 500.0, 1000.0, 2000.0, 4000.0, 8000.0)
        val REFERENCE_RESPONSE_DB = doubleArrayOf(-39.4, -26.2, -16.1, -8.6, -3.2, 0.0, 1.2, 1.0, -1.1)

        /**
         * Допуски по полосам, расширяющиеся к краям — как их и задаёт IEC 61672.
         *
         * У верхнего края работает частотное искажение билинейного преобразования:
         * оно сжимает частотную ось к Найквисту, и на 8 кГц при 44100 Гц дискретный
         * фильтр закономерно лежит примерно на 0.7 дБ ниже аналогового прототипа.
         * Это свойство метода, а не ошибка реализации, и «чинить» его сдвигом
         * полюсов нельзя — так фильтр перестаёт быть A-взвешиванием. Если однажды
         * понадобится точность выше, предыскажение частоты делается отдельным шагом
         * преобразования, а полюса прототипа остаются на месте.
         */
        val REFERENCE_TOLERANCE_DB = doubleArrayOf(2.0, 0.5, 0.5, 0.5, 0.5, 0.5, 0.5, 0.5, 1.5)
    }
}
